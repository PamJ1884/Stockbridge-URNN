#!/usr/bin/env python3
"""Plot Stockbridge U-RNN test sample maps for presentation.

Input:
- .npz files generated by evaluate_stockbridge_urnn_mse.py

Each figure shows:
1. CityCAT max depth over forecast horizon
2. U-RNN max depth over forecast horizon
3. Absolute max-depth error

Units: metres.
"""

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


def event_label_from_npz(path):
    name = path.stem
    parts = name.split("_")
    if len(parts) >= 2:
        return parts[1]
    return name


def plot_one(npz_path, output_dir, depth_vmax=None, error_vmax=None, dry_threshold=0.01):
    data = np.load(npz_path, allow_pickle=True)

    pred = data["pred_m"]
    target = data["target_m"]

    pred_max = np.nanmax(pred, axis=0)
    target_max = np.nanmax(target, axis=0)
    error = np.abs(pred_max - target_max)

    pred_masked = np.where(pred_max >= dry_threshold, pred_max, np.nan)
    target_masked = np.where(target_max >= dry_threshold, target_max, np.nan)
    error_masked = np.where((pred_max >= dry_threshold) | (target_max >= dry_threshold), error, np.nan)

    if depth_vmax is None:
        depth_vmax_local = float(np.nanpercentile(np.concatenate([
            pred_max.reshape(-1),
            target_max.reshape(-1),
        ]), 99.5))
        depth_vmax_local = max(depth_vmax_local, 0.1)
    else:
        depth_vmax_local = depth_vmax

    if error_vmax is None:
        error_vmax_local = float(np.nanpercentile(error.reshape(-1), 99.5))
        error_vmax_local = max(error_vmax_local, 0.02)
    else:
        error_vmax_local = error_vmax

    label = event_label_from_npz(npz_path)

    fig, axes = plt.subplots(1, 3, figsize=(13, 4.4), constrained_layout=True)

    im0 = axes[0].imshow(target_masked, origin="lower", vmin=0, vmax=depth_vmax_local)
    axes[0].set_title(f"CityCAT max depth\n{label}")
    axes[0].set_axis_off()
    cbar0 = fig.colorbar(im0, ax=axes[0], fraction=0.046, pad=0.04)
    cbar0.set_label("Depth [m]")

    im1 = axes[1].imshow(pred_masked, origin="lower", vmin=0, vmax=depth_vmax_local)
    axes[1].set_title("U-RNN max depth")
    axes[1].set_axis_off()
    cbar1 = fig.colorbar(im1, ax=axes[1], fraction=0.046, pad=0.04)
    cbar1.set_label("Depth [m]")

    im2 = axes[2].imshow(error_masked, origin="lower", vmin=0, vmax=error_vmax_local)
    axes[2].set_title("|U-RNN - CityCAT|")
    axes[2].set_axis_off()
    cbar2 = fig.colorbar(im2, ax=axes[2], fraction=0.046, pad=0.04)
    cbar2.set_label("Absolute error [m]")

    fig.suptitle("Stockbridge test event: maximum water depth over T1–T24", fontsize=13)

    output_png = output_dir / f"{label}_max_depth_comparison.png"
    output_pdf = output_dir / f"{label}_max_depth_comparison.pdf"

    fig.savefig(output_png, dpi=300, bbox_inches="tight")
    fig.savefig(output_pdf, bbox_inches="tight")
    plt.close(fig)

    print("Saved:", output_png)
    print("Saved:", output_pdf)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input-dir",
        type=Path,
        default=Path.home() / "flood/03_outputs/Stockbridge-URNN/comet/full_mse_v01/test_eval/sample_maps_npz",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path.home() / "flood/03_outputs/Stockbridge-URNN/comet/full_mse_v01/test_eval/figures",
    )
    parser.add_argument("--depth-vmax", type=float, default=None)
    parser.add_argument("--error-vmax", type=float, default=None)
    parser.add_argument("--dry-threshold", type=float, default=0.01)
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    files = sorted(args.input_dir.glob("*.npz"))
    if not files:
        raise FileNotFoundError(f"No .npz files found in {args.input_dir}")

    print("Input dir:", args.input_dir)
    print("Output dir:", args.output_dir)
    print("Files:", len(files))

    for path in files:
        plot_one(
            path,
            args.output_dir,
            depth_vmax=args.depth_vmax,
            error_vmax=args.error_vmax,
            dry_threshold=args.dry_threshold,
        )


if __name__ == "__main__":
    main()
