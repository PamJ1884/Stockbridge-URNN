#!/usr/bin/env python3
"""Plot georeferenced Stockbridge U-RNN test-event maps.

Input:
- .npz files generated by evaluate_stockbridge_urnn_mse.py

Each figure shows:
1. CityCAT maximum depth over forecast horizon
2. U-RNN maximum depth over forecast horizon
3. Absolute maximum-depth error

Spatial reference:
- EPSG:27700 British National Grid
- Stockbridge 305 x 326 grid
- 5 m resolution

Units: metres.
"""

import argparse
import sys
from pathlib import Path

import numpy as np


# Allow imports from repository root when this script is executed directly.
REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from common.stockbridge_plotting import plot_max_depth_comparison


def event_label_from_npz(path):
    """Return event label such as R019 from an evaluation NPZ filename."""

    name = path.stem
    parts = name.split("_")

    if len(parts) >= 2:
        return parts[1]

    return name


def plot_one(
    npz_path,
    output_dir,
    depth_vmax=None,
    error_vmax=None,
    dry_threshold=0.01,
):
    """Create one standard Stockbridge maximum-depth comparison."""

    data = np.load(npz_path, allow_pickle=True)

    pred = data["pred_m"]
    target = data["target_m"]

    # Scientific calculation retained from the original U-RNN plotter.
    pred_max = np.nanmax(pred, axis=0)
    target_max = np.nanmax(target, axis=0)
    error = np.abs(pred_max - target_max)

    # Retain original automatic colour-scale calculation.
    if depth_vmax is None:
        depth_vmax_local = float(
            np.nanpercentile(
                np.concatenate(
                    [
                        pred_max.reshape(-1),
                        target_max.reshape(-1),
                    ]
                ),
                99.5,
            )
        )
        depth_vmax_local = max(depth_vmax_local, 0.1)
    else:
        depth_vmax_local = depth_vmax

    if error_vmax is None:
        error_vmax_local = float(
            np.nanpercentile(
                error.reshape(-1),
                99.5,
            )
        )
        error_vmax_local = max(error_vmax_local, 0.02)
    else:
        error_vmax_local = error_vmax

    label = event_label_from_npz(npz_path)

    output_png = output_dir / f"{label}_max_depth_comparison.png"

    print()
    print("Event:", label)
    print("Prediction shape:", pred.shape)
    print("Target shape:", target.shape)
    print("Prediction maximum:", float(np.nanmax(pred_max)), "m")
    print("Target maximum:", float(np.nanmax(target_max)), "m")
    print("Depth colour maximum:", depth_vmax_local, "m")
    print("Error colour maximum:", error_vmax_local, "m")

    plot_max_depth_comparison(
        target_max=target_max,
        prediction_max=pred_max,
        output_path=output_png,
        model_name="U-RNN",
        event_label=label,
        depth_vmax=depth_vmax_local,
        error_vmax=error_vmax_local,
        dry_threshold=dry_threshold,
        save_pdf=True,
    )


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--input-dir",
        type=Path,
        default=(
            Path.home()
            / "flood/03_outputs/Stockbridge-URNN/comet/full_mse_v01/test_eval/sample_maps_npz"
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=(
            Path.home()
            / "flood/03_outputs/Stockbridge-URNN/comet/full_mse_v01/test_eval/figures"
        ),
    )

    parser.add_argument(
        "--depth-vmax",
        type=float,
        default=None,
    )

    parser.add_argument(
        "--error-vmax",
        type=float,
        default=None,
    )

    parser.add_argument(
        "--dry-threshold",
        type=float,
        default=0.01,
    )

    args = parser.parse_args()

    args.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    files = sorted(
        args.input_dir.glob("*.npz")
    )

    if not files:
        raise FileNotFoundError(
            f"No .npz files found in {args.input_dir}"
        )

    print("Input dir:", args.input_dir)
    print("Output dir:", args.output_dir)
    print("Files:", len(files))

    for path in files:
        plot_one(
            path,
            args.output_dir,
            depth_vmax=args.depth_vmax,
            error_vmax=args.error_vmax,
            dry_threshold=args.dry_threshold,
        )


if __name__ == "__main__":
    main()
